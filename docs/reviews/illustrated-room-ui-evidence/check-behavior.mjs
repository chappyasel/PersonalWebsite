import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(path.join(process.cwd(),'package.json'));
const {chromium}=require('playwright');
const b=await chromium.launch();
const out='docs/reviews/illustrated-room-ui-evidence';
const base='http://localhost:3330/admin/room-boot-comparison?variant=illustrated';
const result={};
try{
const p=await b.newPage({viewport:{width:390,height:844}});
await p.goto(`${base}&unit=about&theme=light`,{waitUntil:'networkidle'});
await p.getByRole('button',{name:'Explore About',exact:true}).click();
await p.getByRole('dialog').waitFor();
await p.locator('[data-theme-toggle]').click();
await p.waitForFunction(()=>document.querySelector('main.illustrated-room')?.dataset.case==='dark-phone');
if(new URL(p.url()).searchParams.get('theme')!=='dark')throw Error('theme URL did not follow content control');
await p.locator('[data-theme-toggle]').click();
await p.waitForFunction(()=>document.querySelector('main.illustrated-room')?.dataset.case==='light-phone');
await p.locator('[data-theme-toggle]').click();
await p.waitForFunction(()=>document.querySelector('main.illustrated-room')?.dataset.case==='dark-phone');
result.embeddedThemeToggle=true;
await p.getByRole('dialog').getByRole('link',{name:'personal systems',exact:true}).click();
await p.getByRole('dialog').waitFor({state:'hidden'});
await p.waitForFunction(()=>document.querySelector('main.illustrated-room')?.dataset.unit==='systems');
result.hashLinkSelectsShelf=true;
await p.goBack();
await p.waitForFunction(()=>document.querySelector('main.illustrated-room')?.dataset.unit==='about');
result.browserBackRestoresShelf=true;
await p.close();
const f=await b.newPage({viewport:{width:1440,height:900}});
let blocked=0;
await f.route('**/admin/room-boot-comparison/asset?**',async r=>{const q=new URL(r.request().url()).searchParams;if(q.get('file')!=='artwork.svg'){blocked++;await r.abort();}else await r.continue();});
await f.goto(`${base}&unit=talks&theme=light`,{waitUntil:'networkidle'});
await f.getByRole('status').filter({hasText:'illustration is unavailable'}).waitFor();
await f.getByRole('button',{name:'Explore Featured Talks',exact:true}).click();
const content=await f.getByRole('dialog').innerText();
if(content.length<100||!await f.getByRole('dialog').locator('a[href]').count()||!blocked)throw Error('initial detail failure hid content');
result.initialDetailFailureKeepsContent=true;
await f.keyboard.press('Escape');
await f.route('**/admin/room-boot-comparison/asset?**file=artwork.svg',r=>r.abort());
await f.getByRole('navigation').getByRole('button',{name:'Projects',exact:true}).click();
await f.getByRole('status').filter({hasText:'illustration is unavailable'}).waitFor();
await f.getByRole('button',{name:'Explore Projects',exact:true}).click();
if((await f.getByRole('dialog').innerText()).length<100)throw Error('failed SVG hid content');
result.svgFailureKeepsContent=true;
await f.close();
await fs.writeFile(`${out}/behavior.json`,JSON.stringify(result,null,2)+'\n');
console.log(result);
}finally{await b.close();}
